// Build: voice clips -> mp3, assets -> src/assets.js (base64), esbuild bundle, inline into one HTML file.
// usage: node tools/build.mjs            (expects assets/truck.glb from blender/build_truck.py and voice/out/*.wav)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const P = (...a) => path.join(ROOT, ...a);
const FFMPEG = process.env.FFMPEG || 'ffmpeg';

// 1) voice: wav -> mp3 (mono, 56 kbps), skipping ones that are already newer
const lines = JSON.parse(fs.readFileSync(P('voice', 'lines.json'), 'utf8'));
fs.mkdirSync(P('voice', 'mp3'), { recursive: true });
const VOICES = {}, TEXT = {};
for (const l of lines) {
  const wav = P('voice', 'out', l.id + '.wav'), mp3 = P('voice', 'mp3', l.id + '.mp3');
  if (fs.existsSync(wav) && (!fs.existsSync(mp3) || fs.statSync(mp3).mtimeMs < fs.statSync(wav).mtimeMs))
    execFileSync(FFMPEG, ['-v', 'error', '-y', '-i', wav, '-ac', '1', '-ar', '24000', '-b:a', '56k', mp3]);
  VOICES[l.id] = fs.readFileSync(mp3).toString('base64');
  TEXT[l.id] = l.text;
}
// 2) assets module
const glb = fs.readFileSync(P('assets', 'truck.glb')).toString('base64');
fs.writeFileSync(P('src', 'assets.js'),
  `// generated by tools/build.mjs — do not edit\nexport const TRUCK_GLB = ${JSON.stringify(glb)};\nexport const VOICES = ${JSON.stringify(VOICES)};\nexport const VOICE_TEXT = ${JSON.stringify(TEXT)};\n`);
// 3) bundle
const out = await esbuild.build({ entryPoints: [P('src', 'main.js')], bundle: true, format: 'iife', minify: true, write: false, target: ['es2020'], legalComments: 'none' });
const js = out.outputFiles[0].text;
// 4) inline into one page
const html = fs.readFileSync(P('src', 'index.html'), 'utf8').replace('<script>/*APP*/</script>', () => `<script>${js.replace(/<\/script/g, '<\\/script')}</script>`);
fs.mkdirSync(P('dist'), { recursive: true });
const name = '佳文和博文的消防车.html';
fs.writeFileSync(P('dist', name), html);
fs.writeFileSync(P('dist', 'index.html'), html);
fs.mkdirSync(P('docs'), { recursive: true });          // GitHub Pages serves /docs
fs.writeFileSync(P('docs', 'index.html'), html);
fs.writeFileSync(P('docs', '.nojekyll'), '');
console.log(`dist/${name}  ${(html.length / 1048576).toFixed(1)} MB  (truck ${(glb.length * 0.75 / 1048576).toFixed(1)} MB, ${lines.length} voice clips)`);
